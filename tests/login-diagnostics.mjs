import assert from 'node:assert/strict';
import {createLoginDiagnostics} from '../src/login-diagnostics.mjs';
let output;
const d=createLoginDiagnostics({authUrl:'https://auth.test/db/auth',apiRoots:{a:'https://data.test/rest/v1'},standalone:true,render:value=>output=value});
let calls=0;
const response=new Response(JSON.stringify({session:{token:'SECRET-TOKEN'},user:{email:'PRIVATE-EMAIL'}}),{status:200});
const wrapped=d.wrapFetch(async(input,init)=>{calls++;assert.equal(init.body,'PRIVATE-PASSWORD');return response});
d.start();
const returned=await wrapped('https://auth.test/db/auth/get-session?secret=PRIVATE-QUERY',{body:'PRIVATE-PASSWORD'});
assert.equal(returned,response);
assert.equal((await returned.json()).session.token,'SECRET-TOKEN');
await d.finish(true);
assert.equal(calls,1);assert.match(output,/sessao: HTTP 200/);assert.match(output,/sessao: presente/);assert.match(output,/modo: PWA/);
assert.doesNotMatch(output,/SECRET|PRIVATE|auth.test/);
d.start();
await d.wrapFetch(async()=>new Response('null'))('https://auth.test/db/auth/get-session');
await d.finish(true);assert.match(output,/sessao: ausente/);
d.start();
const error=new Error('PRIVATE-NETWORK-DETAILS');
await assert.rejects(d.wrapFetch(async()=>{throw error})('https://auth.test/db/auth/sign-in/email'),e=>e===error);
await d.finish(true);assert.match(output,/falha de rede/);assert.doesNotMatch(output,/PRIVATE/);
d.start();await d.wrapFetch(async()=>new Response('{}'))('https://unrelated.test/private');await d.finish(true);assert.doesNotMatch(output,/HTTP/);
d.start();await d.finish(false);assert.equal(output,'');
console.log('PASS: request/response preserved, session presence and network errors diagnosed; secrets excluded; unrelated requests ignored; success hides report');
